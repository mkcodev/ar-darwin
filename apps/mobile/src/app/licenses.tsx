import { type LicenseEntry, UNKNOWN_LICENSE } from "@ar-darwin/core";
import { space, toNativeTextStyle, touchTarget, typography } from "@ar-darwin/ui";
import { Stack } from "expo-router";
import { FlatList, StyleSheet, Text, View } from "react-native";
import { useSafeAreaInsets } from "react-native-safe-area-context";
import licenses from "../about/licenses.json";
import { t } from "../i18n";
import { useTheme } from "../theme/ThemeProvider";

const ENTRIES: readonly LicenseEntry[] = licenses;

function licenseText(license: string): string {
  return license === UNKNOWN_LICENSE ? t("licenses.unknown") : license;
}

/**
 * The open-source packages the app ships with, generated by `pnpm gen:licenses`
 * (apps/mobile/src/about/licenses.json). A plain list: name, version in Geist Mono, license.
 */
export default function Licenses() {
  const { theme } = useTheme();
  const insets = useSafeAreaInsets();
  const c = theme.color;

  return (
    <>
      <Stack.Screen options={{ title: t("licenses.title") }} />
      <FlatList
        style={{ backgroundColor: c.bg.canvas }}
        contentContainerStyle={[styles.content, { paddingBottom: insets.bottom + space[6] }]}
        contentInsetAdjustmentBehavior="automatic"
        data={ENTRIES}
        keyExtractor={(entry) => `${entry.name}@${entry.version}`}
        ListHeaderComponent={
          <Text style={[styles.intro, { color: c.text.muted }]}>{t("licenses.intro")}</Text>
        }
        renderItem={({ item }) => (
          <View
            accessible
            accessibilityLabel={t("licenses.entry", {
              name: item.name,
              version: item.version,
              license: licenseText(item.license),
            })}
            style={styles.row}
          >
            <Text style={[styles.name, { color: c.text.primary }]}>{item.name}</Text>
            <Text style={[styles.meta, { color: c.text.muted }]}>
              {item.version} · {licenseText(item.license)}
            </Text>
          </View>
        )}
      />
    </>
  );
}

const styles = StyleSheet.create({
  content: { paddingHorizontal: space[5], paddingTop: space[4] },
  intro: { ...toNativeTextStyle(typography.body), marginBottom: space[4] },
  row: { minHeight: touchTarget, justifyContent: "center", paddingVertical: space[2] },
  name: toNativeTextStyle(typography.body),
  meta: toNativeTextStyle(typography.value),
});
